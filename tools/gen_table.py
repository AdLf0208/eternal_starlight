#!/usr/bin/env python3
"""Generate src/table.rs from Eternal Starlight's own biome parameter table.

The jar ships `data/eternal_starlight/dimension/starlight.json`, whose
`generator.biome_source.biome_data_parameters` is the Java
`Climate.ParameterList<Holder<BiomeData>>` the mod's `es:multi_noise` source
answers from. That is a Java type (`ESBiomeSource`), so the port implements it
in Rust (`src/runtime.rs`) against the SDK's `BiomeSource`; this tool copies the
rows of slice 1's four biomes out of the jar, byte for byte, into a compact
Rust table. Nothing is rounded: every interval endpoint is reproduced exactly.

`--check` regenerates into memory and compares with the committed file.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
JAR = (
    ROOT.parent
    / "_shared/licence-cache/eternalstarlight-0.9.1+1.21.1+neoforge.jar"
)
DIMENSION = "data/eternal_starlight/dimension/starlight.json"
OUT = ROOT / "src/table.rs"

# Slice 1: the four biomes whose parameter ranges cover the origin (climate
# 0,0,0), in the order this port lists them in `possible_biomes`. The index in
# this list is the byte stored in each row.
BIOMES = [
    "eternal_starlight:starlight_forest",
    "eternal_starlight:starlight_dense_forest",
    "eternal_starlight:glimmer_scrubland",
    "eternal_starlight:dark_swamp",
]

# The axes, in `mod_api::BiomePoint` order (offset is carried separately).
AXES = ["temperature", "humidity", "continentalness", "erosion", "depth", "weirdness"]


def load_rows() -> tuple[list[dict], dict]:
    with zipfile.ZipFile(JAR) as jar:
        document = json.loads(jar.read(DIMENSION))
    source = document["generator"]["biome_source"]
    if source["type"] != "eternal_starlight:multi_noise":
        raise SystemExit(f"{DIMENSION}: unexpected biome source {source['type']!r}")
    rows = [
        row
        for row in source["biome_data_parameters"]
        if row["biome_data"] in BIOMES
    ]
    if not rows:
        raise SystemExit("no rows for the slice's biomes")
    return rows, source


def interval(value) -> tuple[float, float]:
    if isinstance(value, list):
        return (float(value[0]), float(value[1]))
    return (float(value), float(value))


def build() -> str:
    rows, _ = load_rows()
    tables: list[list[tuple[float, float]]] = [[] for _ in AXES]
    index: list[dict[tuple[float, float], int]] = [{} for _ in AXES]
    encoded = []
    for row in rows:
        parameters = row["parameters"]
        if float(parameters["offset"]) != 0.0:
            raise SystemExit(f"unexpected non-zero offset in {row['biome_data']}")
        axes = []
        for slot, axis in enumerate(AXES):
            span = interval(parameters[axis])
            if not (-2.0 <= span[0] <= span[1] <= 2.0):
                raise SystemExit(f"{axis} interval out of range: {span}")
            known = index[slot].get(span)
            if known is None:
                known = len(tables[slot])
                index[slot][span] = known
                tables[slot].append(span)
            axes.append(known)
        encoded.append((BIOMES.index(row["biome_data"]), axes))
    for slot, table in enumerate(tables):
        tables[slot] = sorted(table)
        rebuilt = {span: i for i, span in enumerate(table)}
        for position, (_, axes) in enumerate(encoded):
            encoded[position][1][slot] = rebuilt[tables[slot][axes[slot]]]

    lines = [
        "// @generated by tools/gen_table.py from",
        f"//   {JAR.relative_to(ROOT.parent)}",
        f"//   {DIMENSION}, generator.biome_source.biome_data_parameters",
        "// Do not edit by hand: `python3 tools/gen_table.py --check` compares this",
        "// file with the jar. Every endpoint is the jar's own (one decimal place in",
        "// the source JSON, written as the shortest f32 that reads back equal).",
        "",
        "use crate::runtime::Row;",
        "",
        "/// The slice's biome ids, in `possible_biomes` order.",
        "pub const BIOMES: [&str; 4] = [",
    ]
    lines += [f'    "{biome}",' for biome in BIOMES]
    lines += ["];", "", "/// The distinct interval of each axis, sorted; a row indexes one per axis.", "#[rustfmt::skip]", "pub const INTERVALS: [&[(f32, f32)]; 6] = ["]
    for table in tables:
        body = ", ".join(f"({fmt(lo)}, {fmt(hi)})" for lo, hi in table)
        lines.append(f"    &[{body}],")
    lines += ["];", "", f"/// Every row of the jar's table for these biomes, in the jar's order.", "#[rustfmt::skip]", f"pub static ROWS: [Row; {len(encoded)}] = ["]
    for biome, axes in encoded:
        lines.append(
            "    Row { biome: %d, axes: [%s], offset: 0.0 }," % (biome, ", ".join(map(str, axes)))
        )
    lines += ["];", ""]
    return "\n".join(lines)


def fmt(value: float) -> str:
    text = repr(value)
    return text if "." in text else text + ".0"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = build()
    if args.check:
        if not OUT.exists():
            print(f"MISSING {OUT}", file=sys.stderr)
            return 1
        if OUT.read_text() != generated:
            print(f"STALE {OUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        rows = sum(1 for line in generated.splitlines() if line.startswith("    Row {"))
        print(f"OK {OUT.relative_to(ROOT)}: {rows} rows")
        return 0
    OUT.write_text(generated)
    rows = sum(1 for line in generated.splitlines() if line.startswith("    Row {"))
    print(f"wrote {OUT.relative_to(ROOT)}: {rows} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
